"""Execution-time SQL rewriting for the Jet dialect."""

import re

from .exceptions import AccessNotSupportedError

__all__ = ['rewrite_limit_to_top']


_RE_LIMIT_OFFSET = re.compile(
    r'\s+LIMIT\s+\?(?P<offset>\s+OFFSET\s+\?)?\s*$', re.IGNORECASE)

#: Matches a trailing ``OFFSET ?`` that carries no ``LIMIT``. peewee only
#: emits a ``LIMIT`` alongside an offset when the dialect declares a
#: ``limit_max``, and Access declares none because it has no LIMIT clause
#: at all -- so ``.offset(n)`` without ``.limit()`` arrives here as a bare
#: OFFSET that the main pattern above cannot see.
_RE_OFFSET_ONLY = re.compile(r'\s+OFFSET\s+\?\s*$', re.IGNORECASE)

#: Matches the leading ``SELECT`` (with optional ``DISTINCT``).
_RE_SELECT_HEAD = re.compile(r'^\s*SELECT\s+(DISTINCT\s+)?', re.IGNORECASE)

#: Matches a compound-select operator. Deliberately case-sensitive: peewee
#: emits SQL keywords in upper case, quotes every identifier in brackets,
#: and binds every value as a parameter, so an unbracketed upper-case
#: ``UNION`` surrounded by whitespace is a real compound operator rather
#: than data.
_RE_COMPOUND = re.compile(r'\s(?:UNION(?:\s+ALL)?|INTERSECT|EXCEPT)\s')

_OFFSET_MESSAGE = (
    'Microsoft Access does not support OFFSET, so result-set '
    'pagination beyond the first page is unavailable.\n'
    'Use keyset (seek) pagination instead: order by an indexed '
    'column and filter on the last value seen, for example\n'
    '    Model.select().where(Model.id > last_id)'
    '.order_by(Model.id).limit(n)\n'
    'Or call pwaccess.paginate(query, page, paginate_by), which pages by '
    'over-fetching with TOP and slicing in Python.')

_COMPOUND_MESSAGE = (
    'Microsoft Access cannot limit a compound (UNION / INTERSECT / EXCEPT) '
    'query. Jet applies TOP to the individual SELECT it is attached to, not '
    'to the combined result, so the rewrite would silently return the wrong '
    'rows.\n'
    'Limit each branch separately, or materialize the compound query and '
    'slice it in Python.')


def rewrite_limit_to_top(sql, params):
    """
    Convert a trailing ``LIMIT ? [OFFSET ?]`` clause into ``SELECT TOP n``.

    peewee binds the limit and offset as query parameters, but Access will
    not accept a parameter marker in a ``TOP`` clause. The values are
    therefore popped off the end of *params* and inlined.

    When the clause cannot be rewritten -- an unparseable limit, or a
    statement that does not begin with ``SELECT`` -- the original statement
    and parameters are returned untouched. Stripping the clause without
    replacing it would silently turn a limited query into a full-table
    scan, which is worse than letting the driver reject the statement.

    :param sql: The statement generated by peewee.
    :param params: The bound parameter list, or ``None``.
    :returns: A ``(sql, params)`` tuple.
    :raises AccessNotSupportedError: for a non-zero ``OFFSET``, which Access
        cannot express, or for a limited compound select, where ``TOP``
        would bind to one branch rather than the whole result.
    """
    match = _RE_LIMIT_OFFSET.search(sql)
    if match is None:
        return _rewrite_bare_offset(sql, params)

    original_params = params
    values = list(params or [])
    trimmed = sql[:match.start()]

    if _RE_COMPOUND.search(trimmed):
        raise AccessNotSupportedError(_COMPOUND_MESSAGE)

    if match.group('offset') is not None:
        if len(values) < 2:
            return sql, original_params
        offset = values.pop()
        limit = values.pop()
        if offset:
            raise AccessNotSupportedError(_OFFSET_MESSAGE)
    else:
        if not values:
            return sql, original_params
        limit = values.pop()

    try:
        top_n = int(limit)
    except (TypeError, ValueError):
        return sql, original_params

    head = _RE_SELECT_HEAD.match(trimmed)
    if head is None:
        return sql, original_params

    distinct = head.group(1) or ''
    return ('SELECT %sTOP %d %s' % (distinct, top_n, trimmed[head.end():]),
            values)


def _rewrite_bare_offset(sql, params):
    """
    Handle a trailing ``OFFSET ?`` that carries no ``LIMIT``.

    ``.offset(0)`` is a no-op and its clause is simply dropped. Any other
    offset is refused, with the same guidance a ``LIMIT ... OFFSET`` would
    give -- without this the statement would reach the driver intact and
    fail with Jet's generic parse error, which names no cause.

    :returns: A ``(sql, params)`` tuple.
    :raises AccessNotSupportedError: for a non-zero offset.
    """
    match = _RE_OFFSET_ONLY.search(sql)
    if match is None:
        return sql, params

    values = list(params or [])
    if not values:
        return sql, params
    if values[-1]:
        raise AccessNotSupportedError(_OFFSET_MESSAGE)
    return sql[:match.start()], values[:-1]
